                    <p class="fw-semibold">Approach</p>
                    <p>We mobilize communities to form self-help groups of 5-10 members, which then evolve into
                        registered Community Based Organizations (CBOs) after six months of operation. Through these
                        CBOs, SMED provides microloans ranging from Rs. 100,000 to Rs. 300,000 monthly interest rates
                        of 1.87% to 2.17% for various purposes including agriculture, dairy farming, small enterprises,
                        green projects, housing improvements, and vocational education.</p>
                    <p>The program emphasizes collective responsibility where group members guarantee each other's
                        loan repayments, requires borrowers to maintain 15% savings of their loan amount, and allows
                        up to three loan cycles within six years per individual. Beyond financial services, SMED focuses
                        on capacity building and organizational development to help marginalized communities aged 18 -
                        70 achieve sustainable development and self-reliance, combining credit facilities with training
                        and support services to break the cycle of poverty through community-led economic
                        development. </p>
