                    <p>The rain-scarce Dry Zone of Sri Lanka is the agricultural heartland of the country. Over half the
                        people living in this region engage in farming or in employment allied to farming. The Dry Zone
                        has experienced some of the worst extreme rainfall events in recent times- causing both flood
                        and drought, often in quick succession. This has caused grave hardship to these agricultural
                        communities affecting crops, irrigation infrastructure and also impacting on the quality and
                        quantity of drinking water available.</p>
                    <p>Climate Resilient Integrated Water Management Project (CRIWMP) is a seven-year project
                        (2017-2024) aimed at strengthening the resilience of Smallholder Farmers in Sri Lanka's Dry
                        Zone to climate variability and extreme events. The project targets poor and vulnerable
                        households in three river basins -the Malwathu, Mi, and Yan (rivers)- which flow through the
                        northern part of the Dry Zone. These river basins are among the most vulnerable to the
                        vagaries of the climate, have a high presence of village irrigation systems and cascade systems
                        on which poor and vulnerable farming populations depend for their livelihoods, and are in
                        areas that significantly lack safe drinking water, which pose a high risk of kidney disease.</p>
                    <p>The project pioneers a holistic approach to enhancing Dry Zone water security and agricultural
                        productivity, and for the first time in a project in Sri Lanka, will include climate smart initiatives
                        designed to combat the effects of extreme weather events on the continuity of irrigation and
                        drinking water supplies.</p>
