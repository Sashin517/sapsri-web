document.getElementById("memberCardsContainer").addEventListener("click", function (event) { viewMemberCard(event) });

const memberCardViewerModal = new bootstrap.Modal("#memberCardViewer");
const memberCardViewer = document.getElementById("memberCardViewer");

function viewMemberCard(event) {

  const card = event.target.closest(".card");
  const memberImage = card.querySelector("img").src;
  const memberName = card.querySelector(".card-title").textContent.trim();
  const memberQualifications = card.querySelector(".card-subtitle").textContent.trim();
  const memberTitle = card.querySelector(".card-text").textContent.trim();
  const memberBio = card.querySelector("p").textContent.trim();
  const memberLinkedIn = card.querySelector("a").href;

  memberCardViewer.querySelector("img").src = memberImage;
  memberCardViewer.querySelector("h5").textContent = memberName;
  memberCardViewer.querySelector("h6").textContent = memberQualifications;
  memberCardViewer.querySelector("span").textContent = memberTitle;
  memberCardViewer.querySelector("p").textContent = memberBio;
  memberCardViewer.querySelector("a").href = memberLinkedIn;

  memberCardViewerModal.show();
}